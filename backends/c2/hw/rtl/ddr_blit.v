/*  Common parameters for all blit cores:
 COMPUTE_OUT_FULL_WIDTH
 BLIT_ADDR_WIDTH
 BLIT_WIDTH
 
  Macros to be defined for this core:
 
 DDR_BLIT_NAME
 TRANSFORMER_CORE
 TRANSFORM_PIPELINE_DELAY
 
 */

module `DDR_BLIT_NAME
               (input clk,
                input 				   rst,
		
                input 				   req,
                input [COMPUTE_OUT_FULL_WIDTH-1:0] data_in,
                input [BLIT_ADDR_WIDTH-1:0] 	   data_addr,  // address in pixels

                output reg 			   ready, 

                input 				   w_ready, // Avalon waitrequest
                output [BLIT_WIDTH-1:0] 	   data_out, 
                output [BLIT_ADDR_WIDTH-1:0] 	   addr_out,
                output 				   we, // Avalon write signal
                input [7:0] 			   burst_count,
                input [64:0] 			   extrain, // Avalon readdatavalid, read_data_in
                output [8:0] 			   extraout // Avalon 'read' signal and burst count
		);

   // Approach:
   // when starting a job, identify left and right l-words overlapping with it,
   // read them, blit the head and the tail, and then sequentially write all the words, including the
   // easy stuff in the middle.

   // E.g., if our job length (after post-processing, potentially, so not necessarily equal to COMPUTE_OUT_FULL_WIDTH) is 57 bytes 
   // (e.g., 19 pixels from a floating point Mandelbrot engine), we'll have 1 head l-word, 1 tail l-word, and 6 full words in the middle,
   // neatly fitting in a single burst.

   //
   // Edge address calculation:
   //   left_edge = (data_addr * 3) / 8 = (data_addr + (data_addr<<1)) >> 3;
   //   right_edge = left_edge + COMPUTE_OUT_LWORD_WIDTH

   wire [31:0] 					   left_edge;
   wire [31:0] 					   right_edge;
   wire [31:0] 					   data_addr_x3;
   assign data_addr_x3 = (data_addr<<1) + data_addr;
   assign left_edge = data_addr_x3 >> 3;
   assign right_edge = left_edge + COMPUTE_OUT_LWORD_WIDTH;


   // Calculating masks for left and right edges:
   //    left_edge byte address = (data_addr * 3),
   //    left edge byte shift   = (data_addr * 3) % 8
   //    right edge byte shift  = ((data_addr + number_of_units) * 3) % 8
   //    total byte shifts = 8-right edge byte shift
   //
   // masks are generated by a ROM (8 variants)
   //
   // Can skip DDR reads if:
   //   left: left edge byte shift == 0
   //   right: total byte shifts == 0
      

   parameter COMPUTE_OUT_FULL_WIDTH = 64;
   parameter COMPUTE_OUT_WIDTH = 7;
   parameter BLIT_ADDR_WIDTH = 29;
   parameter BLIT_WIDTH = 64;

   reg [BLIT_ADDR_WIDTH-1:0] 			   ddr_addr;
   reg [63:0] 					   ddr_data_out;
   wire [63:0] 					   ddr_data_in;
   reg 						   ddr_read;
   reg 						   ddr_write;
   reg [7:0] 					   ddr_burstcount;
   wire 					   ddr_waitrequest;
   wire                                            ddr_readdatavalid;

   assign addr_out = ddr_addr;
   assign data_out = ddr_data_out;
   assign ddr_waitrequest = w_ready;
   
   assign extraout[7:0] = ddr_burstcount;
   assign extraout[8] = ddr_read;
   assign ddr_read_data_in = extrain[63:0];
   assign ddr_readdatavalid = extrain[64];
   
   assign we = ddr_write;


   reg [3:0]                                       ddr_blit_state;
   
   wire                                            ddr_sending_words;
   assign ddr_sending_words = ddr_blit_state == STATE_SHIFTING || ddr_blit_state == STATE_BURSTING;


   always @(posedge clk)
     if (~rst) begin
        ddr_blit_state <= STATE_IDLE;
     end else begin
        case (ddr_blit_state)
	  // In the idle state we're waiting for the input queue to trigger a transaction.
	  //
	  STATE_IDLE: if (req & ready) begin
	     ddr_blit_state <= STATE_START;
	  end
          STATE_START: begin
             ddr_addr <= addr_left_lword;
             ddr_read <= 1'b1;
             ddr_burstcount <= 1;
             ddr_blit_state <= STATE_READ0;
             left_word <= 1;
          end
          STATE_READ0: if (~ddr_waitrequest) begin
             ddr_read <= 1'b0;
             ddr_blit_state <= STATE_READ1;
          end
          STATE_READ1: if (ddr_readdatavalid) begin
             if (left_word) begin
                left_word_data <= ddr_data_in;
                ddr_addr <= addr_right_lword;
                ddr_read <= 1'b1;
                left_word <= 0;
                ddr_blit_state <= STATE_READ0;
             end else begin
                right_word_data <= ddr_data_in;
                ddr_blit_state <= STATE_SHIFTING;
             end
          end // if (ddr_readdatavalid)
          STATE_SHIFTING: begin
             ddr_data_out <= ddr_blended_output;
             ddr_addr <= addr_left_lword;
             ddr_burst_count <= ddr_blended_burst_count;
             ddr_write <= 1;
             ddr_blit_state <= STATE_BURST_WAIT;
          end
          STATE_BURST_WAIT: if (~ddr_waitrequest) begin
	     ddr_data_out <= ddr_blended_output;
	     burst_ctr <= burst_ctr + 1;
	     if (burst_ctr == BURST_SIZE-1) begin
		ddr_write <= 0;
	     end
          end
        endcase
     end

   ////

   reg [COMPUTE_OUT_FULL_WIDTH-1:0]                data_in_shifting;

   // There are three shifting modes for this register:
   //   - job unit width (e.g., 3 bytes for 24bit pixels)
   //   - byte width
   //   - lword width
   reg [FULL_JOB_WIDTH-1:0]                        job_data_in;
   wire [COMPUTE_OUT_WIDTH-1:0]                    data_in_unit;
   assign data_in_unit = data_in_shifting[COMPUTE_OUT_FULL_WIDTH-1:
                                          COMPUTE_OUT_FILL_WIDTH-1-COMPUTE_OUT_WIDTH];
   wire [JOB_UNIT_WIDTH-1:0]                       transformed_unit;

   reg [10:0]                                      shiftcounter;
   reg [10:0]                                      in_shiftcounter;
   reg shift_ready,
       byte_shift_ready,
       lword_shift_ready,
       transformed_ready;
   
   

   `TRANSFORMER_CORE transform (.clk(clk),
                                .rst(rst),
                                .in(data_in_unit),
                                .out(transformed_unit));
   
   // The following machine will first shift transformed job units into a
   // full register, then perform N byte shifts (calculated separately),
   // then, when a DDR transaction is ongoing, will perform lword shifts.
   // 
   // First and last words are blended with their masks separately.
   always @(posedge clk)
     if (~rst) begin
        data_in_shifting <= 0;
        shiftcounter <= 0;
        shift_ready <= 0;
        byte_shift_ready <= 0;
        lword_shift_ready <= 0;
        job_data_in <= 0;
        in_shiftcounter <= 0;
        transformed_ready <= 0;
     end else begin
        if (ready & req) begin
           // Accepted a job, will start processing.
           data_in_shifting <= data_in;
           shiftcounter <= 0;
           shift_ready <= 0;
        end else begin
          if (~in_shift_ready) begin
             if (in_shiftcounter == SHIFT_UNITS_COUNT-1) begin
                in_shift_ready <= 1;
             end
             data_in_shifting[COMPUTE_OUT_FULL_WIDTH-1:COMPUTE_OUT_WIDTH]
               <=
                 data_in_shifting[COMPUTE_OUT_FULL_WIDTH-1-COMPUTE_OUT_WIDTH:0];
          end
          // we don't care if it goes over the top
          in_shiftcounter <= in_shiftcounter + 1; 

          if (in_shiftcounter == TRANSFORM_PIPELINE_DELAY)
            transformed_ready <= 1;
           
          if (~shift_ready & transformed_ready) 
          begin
             if (shiftcounter == SHIFT_UNITS_COUNT-1) begin
                shiftcounter <= 0;
                shift_ready <= 1;
                byte_shift_ready <= 0;
                byte_shift_count <= 0;
                // At the end, job_data_in is left with some left padding,
                // which needs to be addressed by further byte shifting
                // (vs. JOB_UNIT_WIDTH shifting in this stage).
             end else shiftcounter <= shiftcounter + 1;
             job_data_in[JOB_UNIT_WIDTH-1:0] <= transformed_unit;
             job_data_in[FULL_JOB_WIDTH-1:JOB_UNIT_WIDTH] 
               <=
                 job_data_in[FULL_JOB_WIDTH-1-JOB_UNIT_WIDTH:0];
          end else if (~byte_shift_ready) begin // if (~shift_ready)
             if (shiftcounter == byte_shifts - 1) begin
                byte_shift_ready <= 1;
                lword_shift_ready <= 0;
             end else shiftcounter <= shiftcounter + 1;
             job_data_in[FULL_JOB_WIDTH-1:BYTE_WIDTH]
               <=
                 job_data_in[FULL_JOB_WIDTH-1-BYTE_WIDTH:0];
          end else if (~lword_shift_ready & ddr_sending_words) begin
             if (shiftcounter == LWORD_SHIFTS - 1) begin
                lword_shift_ready <= 1;
             end else shiftcounter <= shiftcounter + 1;
             
             job_data_in[FULL_JOB_WIDTH-1:LWORD_WIDTH]
               <=
                 job_data_in[FULL_JOB_WIDTH-1-LWORD_WIDTH:0];
          end
        end // else: !if(ready & req)
     end // else: !if(~rst)
   
   

   

   

   always @(posedge clk)
     if (~rst) begin
	ddr_addr <= 0;
	ddr_data_out <= 0;
	ddr_read <= 0;
	ddr_burstcount <= 0;
	ddr_write <= 0;
     end else begin
     end

endmodule


module mask_rom(input             clk,
                input             rst,
                input [4:0]       shift,
                output reg [63:0] mask);

   always @(posedge clk)
     if (~rst) begin
        mask <= 0;
     end else begin
        case (shift)
          0: mask <= 64'h0000000000000000;
          1: mask <= 64'hff00000000000000;
          2: mask <= 64'hffff000000000000;
          3: mask <= 64'hffffff0000000000;
          4: mask <= 64'hffffffff00000000;
          5: mask <= 64'hffffffffff000000;
          6: mask <= 64'hffffffffffff0000;
          7: mask <= 64'hffffffffffffff00;
        endcase
     end
   
endmodule
